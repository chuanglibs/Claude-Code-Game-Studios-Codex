#!/usr/bin/env python3
"""Generate repository-local Codex entry points from the shared studio sources.

Python 3.9+, standard library only. --check never modifies files.
"""

import argparse
import json
import os
from pathlib import Path, PurePosixPath, PureWindowsPath
import re
import sys


MARKER = "Generated by scripts/sync_codex.py; do not edit."
MANIFEST = "docs/codex/generated-files.json"
RUNTIME = "docs/codex/runtime.md"


def quoted(value):
    """JSON string escaping is compatible with YAML and TOML basic strings."""
    return json.dumps(value, ensure_ascii=False)


def frontmatter(path):
    """Read the source's scalar fields, failing on unsupported YAML constructs.

    This intentionally isn't a general YAML parser. Only name, description, and
    optional agent are consumed; upstream tool/model/context metadata stays there.
    """
    text = path.read_text(encoding="utf-8")
    match = re.match(r"\A---\n(.*?)\n---(?:\n|$)", text, re.S)
    if not match:
        raise ValueError(f"Missing YAML frontmatter: {path}")
    fields = {}
    for key in ("name", "description", "agent"):
        found = re.findall(rf"^{key}:[ \t]*([^\n]*)$", match[1], re.M)
        if len(found) > 1:
            raise ValueError(f"Duplicate {key}: {path}")
        if not found:
            if key != "agent":
                raise ValueError(f"Missing {key}: {path}")
            continue
        value = found[0].strip()
        if value.startswith('"'):
            value = json.loads(value)
        elif value.startswith("'") and value.endswith("'"):
            value = value[1:-1].replace("''", "'")
        elif not value or value[0] in "|>[{&*!":
            raise ValueError(f"Use a one-line scalar for {key}: {path}")
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f"Empty {key}: {path}")
        fields[key] = value
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", fields["name"]):
        raise ValueError(f"Invalid name: {path}")
    if len("studio-" + fields["name"]) > 64:
        raise ValueError(f"Name too long: {path}")
    return fields, match[1]


def link_from(output, target):
    return Path(os.path.relpath(target, PurePosixPath(output).parent)).as_posix()


def collect_outputs(root):
    if not (root / RUNTIME).is_file():
        raise ValueError(f"Missing shared runtime guide: {RUNTIME}")
    outputs = {}
    agents = {}
    for source in sorted((root / ".claude/agents").glob("*.md")):
        fields, _ = frontmatter(source)
        name = fields["name"]
        if name != source.stem or name in agents:
            raise ValueError(f"Agent name must match its unique filename: {source}")
        agents[name] = source.relative_to(root).as_posix()
        instruction = (
            f"Act as the studio's {name} for the delegated task. "
            f"First read {RUNTIME}, then read {agents[name]} from the repository root. "
            "Apply the role's Markdown body with the Codex runtime translations; "
            "its Claude frontmatter is not Codex configuration. "
            "Follow applicable AGENTS.md instructions and the parent's task scope, "
            "file ownership, authorization, and output requirements. "
            "Return evidence and unresolved questions to the parent. "
            "Do not assume tools, persistent memory, or permission grants from the source."
        )
        outputs[f".codex/agents/studio-{name}.toml"] = (
            f"# {MARKER}\n"
            f"name = {quoted('studio-' + name)}\n"
            f"description = {quoted(fields['description'])}\n"
            f"developer_instructions = {quoted(instruction)}\n"
        )

    skills = set()
    for source in sorted((root / ".claude/skills").glob("*/SKILL.md")):
        fields, _ = frontmatter(source)
        name = fields["name"]
        if name != source.parent.name or name in skills:
            raise ValueError(f"Skill name must match its unique directory: {source}")
        skills.add(name)
        role = fields.get("agent")
        if role and role not in agents:
            raise ValueError(f"Unknown agent {role} in {source}")
        output = f".agents/skills/studio-{name}/SKILL.md"
        source_path = source.relative_to(root).as_posix()
        description = "Game studio workflow: " + fields["description"]
        role_instruction = (
            f"3. Use the `{role}` role from "
            f"[its shared brief]({link_from(output, agents[role])}). "
            f"For delegated work, its native Codex name is `studio-{role}`.\n"
            if role else ""
        )
        outputs[output] = (
            f"---\nname: studio-{name}\ndescription: {quoted(description)}\n---\n\n"
            f"<!-- {MARKER} -->\n\n# Studio: {name}\n\n"
            f"1. Read the [Codex runtime guide]({link_from(output, RUNTIME)}).\n"
            f"2. Read the [shared workflow]({link_from(output, source_path)}) "
            "and follow its phases using that guide's translations. "
            "Read referenced documents only when the current phase needs them.\n"
            f"{role_instruction}\n"
            f"Use text following `$studio-{name}` as the workflow arguments. "
            f"Translate references to `/{name}` into `$studio-{name}`; translate "
            "other studio commands the same way. Do not invoke Claude-only tools "
            "or treat its frontmatter as Codex settings.\n"
        )
    if not skills or not agents:
        raise ValueError("Expected nonempty .claude/skills and .claude/agents sources")

    scopes = {}
    for directory in ("src", "design", "docs", "CCGS Skill Testing Framework"):
        source = f"{directory}/CLAUDE.md"
        if (root / source).is_file():
            scopes.setdefault(directory, []).append(source)
    for source in sorted((root / ".claude/rules").glob("*.md")):
        text = source.read_text(encoding="utf-8")
        match = re.match(r"\A---\npaths:\n((?:  - [^\n]+\n)+)---", text)
        if not match:
            raise ValueError(f"Unsupported rule paths frontmatter: {source}")
        for raw in match[1].splitlines():
            pattern = json.loads(raw.removeprefix("  - "))
            if not re.fullmatch(r"[a-zA-Z0-9_/-]+/\*\*", pattern):
                raise ValueError(f"Expected a directory/** rule: {source}")
            directory = pattern[:-3]
            scopes.setdefault(directory, []).append(source.relative_to(root).as_posix())
    for directory, sources in sorted(scopes.items()):
        output = f"{directory}/AGENTS.md"
        references = "".join(
            f"- [{source}]({link_from(output, source)})\n" for source in sources
        )
        outputs[output] = (
            f"<!-- {MARKER} -->\n\n# Instructions for {directory}\n\n"
            "Before changing files here, read these shared instructions and apply "
            f"the [Codex runtime translations]({link_from(output, RUNTIME)}):\n\n"
            f"{references}\n"
            "These are explicit file reads, not automatic Claude imports. "
            "Keep the root AGENTS.md guidance and user-authorized task scope.\n"
        )
    outputs[MANIFEST] = json.dumps(
        {"generated_by": MARKER, "files": sorted(outputs)}, indent=2
    ) + "\n"
    return outputs, len(skills), len(agents)


def safe_destination(root, relative):
    path = PurePosixPath(relative)
    if (path.is_absolute() or PureWindowsPath(relative).drive
            or ".." in path.parts or "\\" in relative):
        raise ValueError(f"Unsafe generated path: {relative}")
    target = root
    for part in path.parts:
        target = target / part
        if target.is_symlink():
            raise ValueError(f"Refusing symlinked output: {relative}")
    return target


def sync(root, check=False):
    outputs, skills, agents = collect_outputs(root)
    manifest = safe_destination(root, MANIFEST)
    old_files = set()
    if manifest.exists():
        previous = json.loads(manifest.read_text(encoding="utf-8"))
        if previous.get("generated_by") != MARKER:
            raise ValueError(f"Refusing unmanaged manifest: {MANIFEST}")
        old_files = set(previous["files"])
    stale = old_files - set(outputs)
    # Validate the entire changeset before writing; never overwrite custom files.
    for relative in sorted(set(outputs) | stale):
        target = safe_destination(root, relative)
        if target.exists() and MARKER not in target.read_text(encoding="utf-8"):
            raise ValueError(f"Refusing unmanaged destination: {relative}")
    changed = [relative for relative, content in outputs.items()
               if not (root / relative).exists()
               or (root / relative).read_text(encoding="utf-8") != content]
    obsolete = [relative for relative in sorted(stale) if (root / relative).exists()]
    if check:
        for relative in changed:
            print(f"OUT OF DATE: {relative}")
        for relative in obsolete:
            print(f"OBSOLETE: {relative}")
        if changed or obsolete:
            print("Run python3 scripts/sync_codex.py to refresh the adapter.", file=sys.stderr)
            return 1
    else:
        for relative in changed:
            target = root / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            with target.open("w", encoding="utf-8", newline="\n") as output:
                output.write(outputs[relative])
        for relative in obsolete:
            (root / relative).unlink()
    print(f"Codex adapter {'verified' if check else 'synchronized'}: "
          f"{skills} skills, {agents} agents, {len(outputs) - skills - agents - 1} scoped instructions.")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report drift without writing")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1],
                        help="Template root (defaults to the script's repository)")
    args = parser.parse_args()
    try:
        return sync(args.root.resolve(), args.check)
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"Codex adapter error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
